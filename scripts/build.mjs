import { mkdir, rm, cp, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const dist = new URL('dist/', root);
const topics = JSON.parse(await readFile(new URL('topics.json', root), 'utf8'));
const game = (await readFile(new URL('game.js', root), 'utf8')).replace(/^export /gm, '');
const app = await readFile(new URL('app.js', root), 'utf8');
const bundle = `// Generated by npm run build. Edit app.js, game.js and topics.json.\n(() => {\n'use strict';\nconst TOPICS = ${JSON.stringify(topics)};\n${game}\n${app}\n})();\n`;
await writeFile(new URL('app.bundle.js', root), bundle);
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
for (const file of ['index.html', 'style.css', 'app.bundle.js', 'assets', '.nojekyll']) {
  await cp(new URL(file, root), new URL(file, dist), { recursive: true });
}
console.log(`Static site ready: ${fileURLToPath(dist)}`);
